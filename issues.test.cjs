const assert=require('node:assert/strict');
const {createState,parseLine,snapshot}=require('./parser.cjs');
const {CodexHaloBridge}=require('./bridge.js');
let tick=0;
const state=createState('issues');
const send=(type,payload)=>parseLine(state,JSON.stringify({type,payload,timestamp:new Date(1800000000000+tick++*1000).toISOString()}));
const start=(id,cmd)=>send('response_item',{type:'function_call',call_id:id,name:'exec',arguments:JSON.stringify({cmd})});
const finish=(id,output)=>send('response_item',{type:'function_call_output',call_id:id,output:JSON.stringify(output)});
const cmd='python -m unittest tests.test_model';
start('fail',cmd);finish('fail',{exit_code:1,output:'Ran 2 tests in 0.1s\nFAILED (failures=1)'});
assert.equal(state.issues.length,1);
const bridge=new CodexHaloBridge();bridge.update(snapshot(state));
assert.equal(bridge.live.panels.find(p=>p.title==='本轮待处理').lines[0],'tests.test_model');
assert.equal(bridge.live.panels.find(p=>p.title==='本轮待处理').priority,true);
start('unknown',cmd);finish('unknown',{output:'done'});
assert.equal(state.issues.length,1,'结果未确认不能清除失败');
start('other','python -m unittest tests.test_other');finish('other',{exit_code:0});
assert.equal(state.issues.length,1,'其他操作成功不能清除失败');
start('again',cmd);finish('again',{exit_code:1});
assert.equal(state.issues.length,1,'重复失败合并');
// Same basename in a different folder is a different operation.
start('different','python -m unittest other.tests.test_model');finish('different',{exit_code:0});
assert.equal(state.issues.length,1);
send('event_msg',{type:'task_complete',turn_id:'one'});
send('event_msg',{type:'task_started',turn_id:'two'});
assert.equal(state.issues.length,1,'跨轮保留未解决问题');
bridge.update(snapshot(state));assert.equal(bridge.live.issues.length,0,'历史失败不冒充本轮问题');
start('fixed',cmd);finish('fixed',{exit_code:0,output:'Ran 2 tests in 0.1s\nOK'});
assert.equal(state.issues.length,0);
assert.ok(state.events.some(e=>e.kind==='resolved'));
bridge.update(snapshot(state));assert.ok(!bridge.live.panels.some(p=>p.title==='本轮待处理'));
const isolated=createState('other');bridge.update(snapshot(isolated));assert.equal(bridge.live.issues.length,0);
start('opaque','node test.cjs');
send('event_msg',{type:'item_completed',item:{id:'opaque',exit_code:1}});
finish('opaque',{output:'some output'});
assert.equal(state.tools.at(-1).state,'error');
assert.equal(state.issues.length,1,'结构化失败不被不明确返回覆盖');
assert.ok(!JSON.stringify(state.issues).includes(cmd),'不暴露原始命令');
const before=state.issues.length;
send('response_item',{type:'function_call',call_id:'browser',name:'js',arguments:JSON.stringify({code:'await tab.getScreenshot()'})});
finish('browser',{isError:true});
assert.equal(state.issues.length,before,'没有可靠重试标识的浏览器错误只记活动历史');
console.log('通过：失败提示、优先展示、重复合并、未知结果保护、精确重试解决、跨轮保留、历史记录及会话隔离');
