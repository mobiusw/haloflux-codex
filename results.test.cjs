const assert=require('node:assert/strict');
const {resultSummary}=require('./results.cjs');
const {createState,parseLine,snapshot}=require('./parser.cjs');
const {CodexHaloBridge}=require('./bridge.js');
const output={content:[{type:'text',text:JSON.stringify({exit_code:0,output:'Ran 9 tests in 0.121s\n\nOK\npassword=private'})}]};
assert.deepEqual(resultSummary(output,'运行 Notebook 测试'),{state:'ok',result:'9 项测试通过'});
assert.equal(resultSummary({exit_code:1,output:'bad'},'测试').state,'error');
assert.equal(resultSummary('Everything looks great','测试').result,'结果未确认');
assert.equal(resultSummary({exit_code:0,output:"const fixture={exit_code:1};"},'读取文件').state,'ok','文件内容中的退出码样例不是执行失败');
const state=createState('notebook');
const send=payload=>parseLine(state,JSON.stringify({type:'response_item',timestamp:'2026-11-09T01:00:00Z',payload}));
send({type:'custom_tool_call',name:'exec',call_id:'n',input:'text(await tools.exec_command({cmd:"python test_notebook_acceptance.py \\\"C:/example/示例数据 - Notebook.ipynb\\\""}))'});
send({type:'custom_tool_call_output',call_id:'n',output});
assert.equal(state.tools[0].target,'示例数据 - Notebook.ipynb');
assert.equal(state.events.at(-1).result,'9 项测试通过');
const bridge=new CodexHaloBridge();bridge.update(snapshot(state));
assert.ok(bridge.live.panels.some(p=>p.lines.includes('9 项测试通过')));
assert.ok(!JSON.stringify(snapshot(state)).includes('password'));
console.log('通过：嵌套工具输出、Notebook对象、结果摘要贯穿事件与圆盘、隐私及未知结果');
